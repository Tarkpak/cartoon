export interface DesktopReleaseNote {
  version: string
  notes: string
  pub_date?: string
}

function parseVersion(version: string) {
  const normalized = version.trim().replace(/^v/i, '')
  const [main = '', prerelease = ''] = normalized.split(/-(.*)/s, 2)
  const parts = main.split('+')[0]!.split('.').map(part => Number.parseInt(part, 10) || 0)
  return { parts, prerelease }
}

export function compareVersions(left: string, right: string): number {
  const a = parseVersion(left)
  const b = parseVersion(right)
  const length = Math.max(a.parts.length, b.parts.length)

  for (let index = 0; index < length; index += 1) {
    const diff = (a.parts[index] ?? 0) - (b.parts[index] ?? 0)
    if (diff !== 0) return diff
  }

  if (a.prerelease === b.prerelease) return 0
  if (!a.prerelease) return 1
  if (!b.prerelease) return -1
  return a.prerelease.localeCompare(b.prerelease, undefined, { numeric: true })
}

function readReleaseNotes(rawJson: unknown): DesktopReleaseNote[] {
  if (!rawJson || typeof rawJson !== 'object') return []
  const releases = (rawJson as { releases?: unknown }).releases
  if (!Array.isArray(releases)) return []

  return releases.filter((item): item is DesktopReleaseNote => {
    return !!item
      && typeof item === 'object'
      && typeof (item as DesktopReleaseNote).version === 'string'
      && typeof (item as DesktopReleaseNote).notes === 'string'
  })
}

// Drop the per-release header generated by scripts/generate-release-notes.mjs.
function stripReleaseHeader(notes: string): string {
  return notes
    .split('\n')
    .filter((line) => {
      const trimmed = line.trim()
      return !/^(版本|范围)：/.test(trimmed) && trimmed !== '更新内容'
    })
    .join('\n')
    .trim()
}

function formatDate(value?: string) {
  if (!value) return ''
  const date = new Date(value)
  return Number.isNaN(date.getTime()) ? '' : date.toISOString().slice(0, 10)
}

/**
 * Merge notes of every release between the installed version (exclusive)
 * and the target version (inclusive). Falls back to the single-release body
 * when the manifest carries no release history.
 */
export function buildCumulativeReleaseNotes(
  currentVersion: string,
  targetVersion: string,
  rawJson: unknown,
  fallbackBody = ''
): string {
  const seen = new Set<string>()
  const releases = readReleaseNotes(rawJson)
    .filter((release) => {
      const key = release.version.replace(/^v/i, '')
      if (seen.has(key)) return false
      seen.add(key)
      return (!currentVersion || compareVersions(release.version, currentVersion) > 0)
        && compareVersions(release.version, targetVersion) <= 0
    })
    .sort((left, right) => compareVersions(right.version, left.version))

  if (releases.length === 0) return fallbackBody

  return releases
    .map((release) => {
      const date = formatDate(release.pub_date)
      const title = `v${release.version.replace(/^v/i, '')}${date ? `（${date}）` : ''}`
      const body = stripReleaseHeader(release.notes)
      return body ? `${title}\n${body}` : title
    })
    .join('\n\n')
}
